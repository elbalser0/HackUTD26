-- Argus initial schema for PostgreSQL + TimescaleDB (Tiger Cloud).
-- Applied by `breakglass migrate-schema` under an advisory lock; unqualified names use the connection search_path.

CREATE TABLE records (
    id TEXT PRIMARY KEY,
    environment TEXT NOT NULL,
    resource_address TEXT NOT NULL,
    resource_type TEXT NOT NULL,
    attribute TEXT NOT NULL,
    change_kind TEXT NOT NULL,
    baseline_json TEXT,
    observed_json TEXT,
    scope_key TEXT NOT NULL,
    fingerprint TEXT NOT NULL,
    summary TEXT NOT NULL,
    first_detected_at TIMESTAMPTZ NOT NULL,
    last_detected_at TIMESTAMPTZ NOT NULL,
    reporter TEXT,
    reason TEXT,
    reported_at TIMESTAMPTZ,
    intent TEXT NOT NULL DEFAULT 'unset',
    intent_note TEXT,
    intent_updated_at TIMESTAMPTZ,
    resolution TEXT NOT NULL DEFAULT 'open',
    resolution_reason TEXT,
    resolved_at TIMESTAMPTZ,
    superseded_by TEXT,
    last_check_status TEXT NOT NULL,
    last_check_at TIMESTAMPTZ,
    evidence_source TEXT NOT NULL
);
CREATE INDEX idx_records_open_fp ON records(environment, fingerprint, resolution);
CREATE INDEX idx_records_scope ON records(environment, scope_key, resolution);

CREATE TABLE apply_runs (
    id TEXT PRIMARY KEY,
    environment TEXT NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL,
    plan_fingerprint TEXT,
    proposed_changes_json TEXT NOT NULL,
    warnings_json TEXT NOT NULL,
    check_status TEXT NOT NULL,
    coverage_note TEXT NOT NULL,
    ack_outcome TEXT NOT NULL,
    ack_note TEXT,
    completed_at TIMESTAMPTZ,
    started_at TIMESTAMPTZ,
    reviewer TEXT,
    reviewer_assurance TEXT,
    rationale TEXT
);

CREATE TABLE scans (
    id TEXT PRIMARY KEY,
    environment TEXT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL,
    detail TEXT
);

-- A hypertable's unique indexes must include the time column, so (created_at, id) cannot enforce
-- ID-only uniqueness. event_keys does, and is written in the same transaction as every event.
CREATE TABLE event_keys (
    id TEXT PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE events (
    id TEXT NOT NULL,
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY,   -- deterministic tie-breaker, not a global commit order
    created_at TIMESTAMPTZ NOT NULL,
    environment TEXT NOT NULL,
    record_id TEXT,
    run_id TEXT,
    kind TEXT NOT NULL,
    actor TEXT,
    actor_assurance TEXT NOT NULL,
    data_json TEXT NOT NULL,
    intent TEXT,     -- typed analytics dimensions, copied from data_json at insert
    decision TEXT,
    outcome TEXT,
    PRIMARY KEY (created_at, id)
);
SELECT create_hypertable('events', 'created_at', chunk_time_interval => INTERVAL '7 days');
CREATE INDEX idx_events_record ON events(record_id, created_at, seq);
CREATE INDEX idx_events_run ON events(run_id, created_at, seq);
CREATE INDEX idx_events_env_time ON events(environment, created_at DESC);
